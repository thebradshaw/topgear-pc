#!/usr/bin/env python3
"""Draws the launcher's START button word as pixel art in the spirit of the Top Gear logo:
blocky letters leaning forward, a red-to-gold face, a purple outline and a purple-and-black
block underneath, with speed stripes. Writes src/launcher_start.h (RGBA).

Usage: gen_launcher_start.py [preview.png]   (needs Pillow and numpy)
"""
import sys
import numpy as np
from PIL import Image, ImageDraw

U = 8           # stroke width in pixels
H = 5 * U       # letter height
SLANT = 0.42    # pixels right per pixel up
GAP = 3         # units between letters

# Letters as rectangles (x0, y0, x1, y1) or polygons, in stroke units on a 5-unit grid.
LETTERS = {
    "S": [(0, 0, 5, 1), (0, 0, 1, 3), (0, 2, 5, 3), (4, 2, 5, 5), (0, 4, 5, 5)],
    "T": [(0, 0, 6, 1), (2.5, 0, 3.5, 5)],
    "A": [(0, 0, 5, 1), (0, 0, 1, 5), (4, 0, 5, 5), (0, 2, 5, 3)],
    "R": [(0, 0, 5, 1), (0, 0, 1, 5), (4, 0, 5, 3), (0, 2, 5, 3), [(2.6, 3), (3.8, 3), (5.2, 5), (4, 5)]],
}
WIDTH = {"S": 5, "T": 6, "A": 5, "R": 5.2}

word = "START"
cols = sum(WIDTH[c] for c in word) + GAP * 0.5 * (len(word) - 1)
pad = 8
stripe_h = int(U * 1.3)
canvas_h = H + 2 + stripe_h + pad * 2 + 6
canvas_w = int(cols * U + canvas_h * SLANT) + pad * 2 + 8

face = Image.new("L", (canvas_w, canvas_h), 0)
d = ImageDraw.Draw(face)
top = pad

def shear(x, y):
    return (x + (top + H - y) * SLANT, y)

x0 = pad
for c in word:
    for part in LETTERS[c]:
        if isinstance(part, tuple):
            a, b, e, f = part
            pts = [(a, b), (e, b), (e, f), (a, f)]
        else:
            pts = part
        d.polygon([shear(x0 + px * U, top + py * U) for px, py in pts], fill=255)
    x0 += WIDTH[c] * U + GAP * 0.5 * U

# Speed stripes: a bar under the word, cut by leaning slits, fading out to the right.
by0, by1 = top + H + 3, top + H + 3 + stripe_h
bx0, bx1 = pad + U * 1, x0 - GAP * 0.5 * U
d.polygon([shear(bx0, by0), shear(bx1, by0), shear(bx1, by1), shear(bx0, by1)], fill=255)
slit = Image.new("L", face.size, 0)
ds = ImageDraw.Draw(slit)
step = 7
for i, sx in enumerate(np.arange(bx0 + U * 3, bx1 - 2, step)):
    w = 1 + min(3, i // 4)  # slits widen towards the end
    ds.polygon([shear(sx, by0), shear(sx + w, by0), shear(sx + w, by1), shear(sx, by1)], fill=255)
m = (np.array(face) > 127) & ~(np.array(slit) > 127)

def dilate(a, r):
    out = a.copy()
    for dy in range(-r, r + 1):
        for dx in range(-r, r + 1):
            if dx * dx + dy * dy <= r * r + r:
                out |= np.roll(np.roll(a, dy, 0), dx, 1)
    return out

def shift(a, dx, dy):
    return np.roll(np.roll(a, dy, 0), dx, 1)

outline = dilate(m, 2)
depth = 5
block = np.zeros_like(m)
for k in range(1, depth + 1):
    block |= shift(outline, k // 2, k)
shadow = dilate(block, 1) | shift(block, 1, 2) | shift(block, 0, 2)

PURPLE = (104, 56, 216)
LILAC = (136, 136, 248)
BLACK = (0, 0, 0)
RAMP = [(232, 72, 72), (232, 88, 72), (232, 104, 56), (232, 120, 40), (232, 136, 40),
        (248, 152, 24), (248, 184, 24), (248, 216, 0)]
BAYER = np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]) / 16.0

img = np.zeros((canvas_h, canvas_w, 4), np.uint8)
img[shadow] = BLACK + (255,)
img[block] = PURPLE + (255,)
img[outline] = PURPLE + (255,)
# A light edge along the top of the outline, as on the logo.
light = outline & ~shift(outline, 0, 1) & ~m
img[light] = LILAC + (255,)
ys, xs = np.nonzero(m)
lo, hi = xs.min(), xs.max()
for y, x in zip(ys, xs):
    # Red at the left to gold at the right, a little lighter towards the top; dithered.
    t = (x - lo) / max(1, hi - lo) * 0.85 + (1 - (y - top) / H) * 0.15
    v = t * (len(RAMP) - 1) + (BAYER[y % 4, x % 4] - 0.5) * 0.9
    img[y, x] = RAMP[int(np.clip(round(v), 0, len(RAMP) - 1))] + (255,)

# Crop to the drawing.
alpha = img[:, :, 3] > 0
ys, xs = np.nonzero(alpha)
img = img[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
h, w = img.shape[:2]
if len(sys.argv) > 1:
    Image.fromarray(img, "RGBA").resize((w * 4, h * 4), Image.NEAREST).save(sys.argv[1])
with open("src/launcher_start.h", "w") as f:
    f.write("// Generated by tools/gen_launcher_start.py: the Start button's word, RGBA.\n")
    f.write("#define START_ART_W %d\n#define START_ART_H %d\n" % (w, h))
    f.write("static const unsigned char kStartArt[%d] = {\n" % (w * h * 4))
    data = img.tobytes()
    for i in range(0, len(data), 32):
        f.write("  " + ",".join(str(v) for v in data[i:i + 32]) + ",\n")
    f.write("};\n")
print(w, h)
