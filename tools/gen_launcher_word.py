#!/usr/bin/env python3
"""Renders the launcher's PLAY word to src/launcher_word.h as an 8-bit coverage bitmap.

Font: Inter Display Black Italic (SIL Open Font License 1.1, https://rsms.me/inter/).
Usage: gen_launcher_word.py [font.otf]  (needs Pillow)
"""
import sys
from PIL import Image, ImageDraw, ImageFont

font_path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/inter/InterDisplay-BlackItalic.otf"
word, height, ss = "PLAY", 64, 4
font = ImageFont.truetype(font_path, height * ss)
l, t, r, b = font.getbbox(word)
pad = 2 * ss
im = Image.new("L", (r - l + 2 * pad, b - t + 2 * pad), 0)
ImageDraw.Draw(im).text((pad - l, pad - t), word, font=font, fill=255)
im = im.resize((im.width // ss, im.height // ss), Image.LANCZOS)
w, h = im.size
data = im.tobytes()
with open("src/launcher_word.h", "w") as f:
    f.write("// Generated by tools/gen_launcher_word.py: \"%s\" in Inter Display Black Italic\n" % word)
    f.write("// (SIL Open Font License 1.1), as 8-bit coverage.\n")
    f.write("#define PLAY_WORD_W %d\n#define PLAY_WORD_H %d\n" % (w, h))
    f.write("static const unsigned char kPlayWord[%d] = {\n" % (w * h))
    for i in range(0, len(data), 24):
        f.write("  " + ",".join(str(v) for v in data[i:i + 24]) + ",\n")
    f.write("};\n")
print(w, h)
